import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { runCompetitive } from "./harness.js";
import { runMemoryBench } from "./memory-bench.js";
import { FAULTS } from "./simulator.js";

const repoDir = fileURLToPath(new URL("../..", import.meta.url));
const pct = (x) => `${(x * 100).toFixed(1)}%`;

function md(headers, rows) {
  return [`| ${headers.join(" | ")} |`, `|${headers.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");
}

async function main() {
  const trials = Number(process.argv[2] ?? 1000);
  const faulty = await runCompetitive({ trials, faultRate: 0.3, readFaultRate: 0.02, seed: 42 });
  const clean = await runCompetitive({ trials, faultRate: 0, readFaultRate: 0, seed: 42 });
  const memory = runMemoryBench();
  const link = (r) => `[${r.product}](${r.url})`;
  const bold = (r, v) => (r.name === "trust-layer" || r.name === "memory-js" ? `**${v}**` : `${v}`);

  const out = [];
  out.push(`# Competitive benchmark results`, ``,
    `Generated by \`npm run eval:competitive\` (${trials} trials, seed 42). Same seeded fault schedule for every row; ground truth from the simulator's own store.`, ``,
    `## Products and the behavior benchmarked`, ``,
    md(["product", "pattern", "documented behavior modeled", "note"], faulty.results.map((r) => [link(r), r.pattern, r.behavior, r.note])), ``,
    `## Accuracy under fault injection`, ``,
    `${trials} create-actions, 30% fault rate split evenly across: fake-200 (nothing stored), truncated on save, wrong-record (stored, returned id points nowhere), timeout after the write happened, transient 503 before it. Read path 2% flaky.`, ``,
    md(["product", "silent failures", "caught", "catch rate", "orphaned writes", "escalated", "duplicates", "partials left", "end state correct"],
      faulty.results.map((r) => [link(r), bold(r, r.silentFailures), r.caught, bold(r, pct(r.catchRate)), r.orphans, r.escalations, bold(r, r.duplicates), r.partialsLeft, bold(r, pct(r.endStateCorrectRate))])), ``,
    `- **silent failures**: reality was wrong (no record, partial, unreachable, or duplicated) and the product told the agent "done"`,
    `- **orphaned writes**: the product said "failed" but a record was written — the agent doesn't know it exists`,
    `- **escalated**: reported "unknown" and handed to a human instead of guessed`,
    `- **end state correct**: what the agent was told matches reality and nothing half-done remains`, ``,
    `## Silent failures by fault type (missed / injected)`, ``,
    md(["product", ...FAULTS], faulty.results.map((r) => [link(r), ...FAULTS.map((f) => bold(r, `${r.byFault[f].silent}/${r.byFault[f].n}`))])), ``,
    `## Time: cost per action (simulated API latency — write 120ms, read 60ms, delete 100ms)`, ``,
    md(["product", "calls/action (faulty)", "ms/action (faulty)", "calls/action (clean)", "ms/action (clean)"],
      faulty.results.map((r, i) => [link(r), r.apiCallsPerAction.toFixed(2), r.latencyMsPerAction.toFixed(0), clean.results[i].apiCallsPerAction.toFixed(2), clean.results[i].latencyMsPerAction.toFixed(0)])), ``,
    `## Memory: ${memory.services} services, ${memory.observations} observations, ${memory.ownershipChanges} real ownership changes, top-${memory.topK} retrieval`, ``,
    md(["product", "stored", "queries with contradictory context", "current owner correct", "changes detected", "confirmations mistaken for changes", "history retained", "LLM calls per add", "deterministic"],
      memory.rows.map((r) => [link(r), r.stored, bold(r, `${r.contradictoryContexts} (${pct(r.contradictoryContexts / memory.services)})`), r.currentCorrect === null ? "n/a — model must pick" : `${r.currentCorrect}/${memory.services}`, bold(r, `${r.revisionsDetected}/${memory.ownershipChanges}`), r.falseRevisions === null ? "n/a" : r.falseRevisions, bold(r, r.historyRetained), r.llmCallsPerAdd, r.deterministic ? "yes" : "no"])), ``,
    ...memory.rows.filter((r) => r.note).map((r) => `- ${r.product}: ${r.note}`), ``,
    `## Caveats`, ``,
    `- Trust-layer "orphaned writes" are all wrong-record cases: it correctly reports \`false\`, but the stray record lives under an id it was never given, so it cannot reverse it. A content search as a second source would close this; not implemented.`,
    `- Trust-layer escalations are timeouts plus read-path failures. Those go to a human instead of being guessed. That is the design, and it is a real cost.`,
    `- Retry rows are pinned to 3 attempts (LangGraph's default; Temporal's default is unlimited). More attempts only add duplicates.`,
    `- LLM-judge and mem0 are modeled at their best case (perfect decisions, zero latency). Real runs can only be worse on the same input.`,
    `- Vector-store top-k ties are broken by insertion order; any tie-break yields contradictory context whenever two owners are among the k most similar notes.`, ``,
  );
  const text = out.join("\n");
  console.log(text);

  await writeFile(join(repoDir, "eval", "competitive", "RESULTS.md"), text + "\n");
  const outDir = join(repoDir, "output");
  await mkdir(outDir, { recursive: true });
  const outPath = join(outDir, `competitive-${new Date().toISOString().replace(/[:.]/g, "-")}.json`);
  await writeFile(outPath, JSON.stringify({ faulty, clean, memory }, null, 2));
  console.log(`Wrote eval/competitive/RESULTS.md and ${outPath}`);
}

main();
